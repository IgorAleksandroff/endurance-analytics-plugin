#!/usr/bin/env python3
"""Write the listing text (listing.json) and the tool list (agent-surface.json) into every place that carries them.

One source for both directories (OpenAI and Anthropic): manifests, marketplace, both READMEs and the text
for the Claude connector listing. Edit listing.json, never the generated fields.

  scripts/sync-listing.py                       write the generated files
  scripts/sync-listing.py --check               fail when a generated file is out of date (the build runs it)
  scripts/sync-listing.py --surface-from <file> refresh agent-surface.json from the server's export
                                                (<back>/docs/api/agent_surface.json)
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugins" / "endurance"
LISTING = ROOT / "listing.json"
SURFACE = ROOT / "agent-surface.json"
MARK_START, MARK_END = "<!-- listing:start (scripts/sync-listing.py) -->", "<!-- listing:end -->"


def load(path):
    return json.loads(path.read_text(encoding="utf-8"))


def dump(doc):
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def model_tools():
    """Tools the model sees; app-only ones are called by an MCP Apps view through the host."""
    return [t["name"] for t in load(SURFACE)["tools"] if not t["app_only"]]


def long_text(listing):
    return "\n\n".join(listing["longDescription"])


def openai_manifest(listing):
    doc = load(PLUGIN / "plugin.json")
    for key in ("name", "version", "description", "author", "homepage", "repository", "license", "keywords"):
        doc[key] = listing[key]
    oai = doc["extensions"]["com.openai"]
    iface = oai["interface"]
    iface["displayName"] = listing["displayName"]
    iface["shortDescription"] = listing["shortDescription"]
    iface["longDescription"] = long_text(listing)
    iface["defaultPrompt"] = listing["defaultPrompt"]
    oai["publication"]["release_notes"] = listing["releaseNotes"]
    return dump(doc)


def claude_manifest(listing):
    manifest = {key: listing[key] for key in (
        "name", "displayName", "version", "description", "author", "homepage", "repository", "license", "keywords")}
    manifest["privacyPolicyUrl"] = load(PLUGIN / "plugin.json")["extensions"]["com.openai"]["interface"]["privacyPolicyURL"]
    return dump(manifest)


def marketplace(listing):
    doc = load(ROOT / ".claude-plugin" / "marketplace.json")
    doc["metadata"].update(description=listing["description"], version=listing["version"])
    (entry,) = doc["plugins"]
    entry.update({key: listing[key] for key in ("name", "description", "version", "author", "homepage", "keywords")})
    return dump(doc)


def plugin_readme(listing):
    """The plugin folder's README: Anthropic's directory shows it as the listing; it ships in both packages."""
    prompts = "\n".join(f"- {p}" for p in listing["defaultPrompt"])
    return f"""# {listing["displayName"]}

{long_text(listing)}

## Use it

Connect the plugin and sign in to your Endurance Analytics account when the
browser opens. Then ask, for example:

{prompts}

## Data

{listing["dataUse"]}

Setup guide: {listing["homepage"]}.
Privacy policy: https://endurance-analytics.com/en/privacy.
Terms: https://endurance-analytics.com/en/terms.
"""


def repo_readme(listing):
    text = (ROOT / "README.md").read_text(encoding="utf-8")
    head, rest = text.split(MARK_START)
    _, tail = rest.split(MARK_END)
    links = listing["listings"]
    block = f"""{MARK_START}
{long_text(listing)}

Official listings: [ChatGPT]({links["chatgpt"]}) · [Claude]({links["claude"]})
{MARK_END}"""
    return head + block + tail


def connector_listing(listing):
    """Fields of the Claude connector listing (claude.ai/directory/manage), pasted by hand."""
    tools = "\n".join(model_tools())
    return f"""# Claude connector listing

Generated by `scripts/sync-listing.py` from `listing.json` and `agent-surface.json`.
Paste into the listing at https://claude.ai/directory/manage after a release
that changes them; a reviewer approves the edit.

## Tagline

{listing["description"]}

## Description

{long_text(listing)}

## Tool names

{tools}

## Links

- Documentation: {listing["homepage"]}
- Privacy policy: https://endurance-analytics.com/en/privacy
- Support: mailto:contact@endurance-analytics.com
"""


def outputs(listing):
    return {
        PLUGIN / "plugin.json": openai_manifest(listing),
        PLUGIN / ".claude-plugin" / "plugin.json": claude_manifest(listing),
        ROOT / ".claude-plugin" / "marketplace.json": marketplace(listing),
        PLUGIN / "README.md": plugin_readme(listing),
        ROOT / "README.md": repo_readme(listing),
        ROOT / "connector-listing.md": connector_listing(listing),
    }


def refresh_surface(src):
    SURFACE.write_text(Path(src).read_text(encoding="utf-8"), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--surface-from")
    args = parser.parse_args()
    if args.surface_from:
        refresh_surface(args.surface_from)
    stale = []
    for path, content in outputs(load(LISTING)).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("out of date, run scripts/sync-listing.py: " + ", ".join(map(str, stale)))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
